import './dom-setup';
import React from 'react';
import test from 'node:test';
import assert from 'node:assert/strict';
import {render,screen,fireEvent,within,waitFor,cleanup,act} from '@testing-library/react';
import App from '../src/App';
import {downloads} from './dom-setup';
const navigate=async(name:string)=>{fireEvent.click(screen.getAllByRole('button',{name})[0]);await act(async()=>{await new Promise(r=>setTimeout(r,10));});};
const close=()=>fireEvent.click(screen.getByRole('button',{name:'Close dialog'}));
test('The four connected user flows, local persistence, and exports',async(t)=>{
 render(<App/>);
 await t.test('1. Search Scorpio and follow traditional Mars and modern Pluto',async()=>{
  fireEvent.change(screen.getByLabelText('Search the atlas'),{target:{value:'Scorpio'}});
  const search=document.querySelector('.search-results')!;
  fireEvent.click(within(search as HTMLElement).getAllByRole('button',{name:/Scorpio/})[0]);
  let dialog=await screen.findByRole('dialog',{name:'Scorpio'});
  assert.ok(within(dialog).getByText('TRADITIONAL RULER'));
  assert.ok(within(dialog).getByText('MODERN RULER'));
  fireEvent.click(within(dialog).getByRole('button',{name:/TRADITIONAL RULER.*Mars/}));
  dialog=await screen.findByRole('dialog',{name:'Mars'});
  assert.ok(within(dialog).getByText(/Action · desire · courage/));
  fireEvent.click(within(dialog).getByRole('button',{name:'Back'}));
  dialog=await screen.findByRole('dialog',{name:'Scorpio'});
  fireEvent.click(within(dialog).getByRole('button',{name:/MODERN RULER.*Pluto/}));
  dialog=await screen.findByRole('dialog',{name:'Pluto'});
  assert.ok(within(dialog).getByText(/Transformation · depth · power/));
  close();
 });
 const create=async(name:string,date:string,time:string)=>{
  await navigate('My Charts');fireEvent.click(screen.getByRole('button',{name:'New birth chart'}));
  const dialog=await screen.findByRole('dialog',{name:'A moment written in the stars'});
  fireEvent.change(within(dialog).getByLabelText('Profile name'),{target:{value:name}});
  fireEvent.change(within(dialog).getByLabelText('Birth date'),{target:{value:date}});
  fireEvent.change(within(dialog).getByLabelText('Local birth time'),{target:{value:time}});
  fireEvent.click(within(dialog).getByLabelText('I confirm this location and time zone'));
  fireEvent.click(within(dialog).getByRole('button',{name:/Create & save birth chart/}));
  await waitFor(()=>assert.equal(screen.queryByRole('dialog',{name:'A moment written in the stars'}),null));
  assert.ok(screen.getByRole('heading',{name:`${name}’s birth chart`}));
 };
 await t.test('2. Enter birth details, inspect Moon, Ascendant, and chart ruler',async()=>{
  await create('Aster','2000-01-01','12:00');
  const big3=document.querySelector('.big-three')!;
  assert.match(big3.textContent||'',/Scorpio/);assert.match(big3.textContent||'',/Aries/);
  fireEvent.click(within(big3 as HTMLElement).getByRole('button',{name:/YOUR INNER WORLD/}));
  assert.equal(document.querySelector('.placement-title h2')!.textContent,'Moon');
  fireEvent.click(screen.getByRole('button',{name:'Table'}));
  assert.ok(screen.getByRole('table',{name:'Accessible planetary position table'}));
  fireEvent.click(screen.getByRole('button',{name:'Explore Mars'}));
  const dialog=await screen.findByRole('dialog',{name:'Mars'});
  assert.match(dialog.textContent||'',/Aster/);assert.match(dialog.textContent||'',/Aquarius/);assert.match(dialog.textContent||'',/House 11/);
  close();assert.equal(JSON.parse(localStorage.getItem('atlas-profiles')!).length,1);
  await create('Rowan','1995-11-07','14:30');
 });
 await t.test('3. Compare signs, then saved charts and the underlying aspects',async()=>{
  await navigate('Compatibility');
  fireEvent.change(screen.getByLabelText('First zodiac sign'),{target:{value:'Aries'}});
  assert.ok(screen.getByRole('heading',{name:'Aries & Pisces'}));
  fireEvent.click(screen.getByRole('button',{name:'Communication'}));
  assert.ok(screen.getByRole('heading',{name:'How the conversation begins'}));
  fireEvent.click(screen.getByRole('button',{name:'Compare Birth Charts'}));
  assert.ok(screen.getByRole('heading',{name:'Aster & Rowan'}));
  assert.ok(document.querySelectorAll('.syn-evidence button').length>0);
  const aspectButton=document.querySelector('.syn-evidence button') as HTMLButtonElement;
  fireEvent.click(aspectButton);assert.ok(screen.getByRole('dialog'));close();
  assert.ok(document.querySelector('.aspect-table tbody tr'));
  fireEvent.click(screen.getByRole('button',{name:'Composite'}));
  assert.ok(screen.getByText('Planetary midpoint composite'));
 });
 await t.test('4. Select a date, inspect Moon/events, switch time zones, export event',async()=>{
  await navigate('Calendar');
  fireEvent.change(screen.getByLabelText('Choose calendar date'),{target:{value:'2024-04-08'}});
  await waitFor(()=>assert.ok(document.querySelector('.day-event-list')!.textContent!.includes('New Moon')),{timeout:5000});
  assert.ok(document.querySelector('.selected-day-moon'));
  fireEvent.change(screen.getByLabelText('Calendar time zone'),{target:{value:'America/New_York'}});
  await waitFor(()=>assert.ok(document.querySelector('.day-event-list')!.textContent!.includes('EDT')));
  const list=document.querySelector('.day-event-list') as HTMLElement;
  fireEvent.click(within(list).getByRole('button',{name:/New Moon/}));
  const dialog=await screen.findByRole('dialog',{name:'New Moon'});
  assert.match(dialog.textContent||'',/America\/New_York/);
  fireEvent.click(within(dialog).getByRole('button',{name:'Export .ics event'}));
  assert.equal(downloads.at(-1)?.filename,'new-moon.ics');
  const contents=await downloads.at(-1)!.blob!.text();assert.match(contents,/DTSTART:20240408T182125Z/);
  close();fireEvent.click(screen.getByRole('button',{name:'Moon tracker'}));
  assert.equal(document.querySelectorAll('.eight-phases>div').length,8);
  assert.ok(screen.getByRole('heading',{name:'Next principal phases'}));
 });
 await t.test('Favorites and dark theme persist locally',async()=>{
  await navigate('Explore');fireEvent.click(screen.getByRole('button',{name:'Save Scorpio to favorites'}));
  assert.ok(JSON.parse(localStorage.getItem('atlas-favorites')!).includes('Scorpio'));
  fireEvent.click(screen.getByRole('button',{name:'Use dark theme'}));
  assert.equal(document.documentElement.dataset.theme,'dark');
 });
 cleanup();
});
